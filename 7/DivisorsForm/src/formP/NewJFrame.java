    public static int countDivisors(int n) {
        if (n < 0) {
            n = -n;
        }
        if (n == 0) {
            return 0;
        }
        int count = 0;
        for (int i = 1; i <= n; i++) {
            if (n % i == 0) {
                count++;
            }
        }
        return count;
    }

