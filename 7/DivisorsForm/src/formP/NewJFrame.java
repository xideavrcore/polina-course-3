    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {
        try {
            String text = jTextArea1.getText().trim();
            if (text.isEmpty()) {
                jTextArea2.setText("Введите числа.");
                return;
            }
            String[] parts = text.split("[\\s,;]+");
            StringBuilder sb = new StringBuilder();
            for (int i = 0; i < parts.length; i++) {
                int n = Integer.parseInt(parts[i]);
                if (n == 0) {
                    break;
                }
                sb.append("Число ").append(n)
                        .append(": делителей = ").append(countDivisors(n))
                        .append("\n");
            }
            if (sb.length() == 0) {
                jTextArea2.setText("Нет чисел до 0.");
            } else {
                jTextArea2.setText(sb.toString());
            }
        } catch (NumberFormatException ex) {
            jTextArea2.setText("Ошибка: введите целые числа.");
        }
    }

