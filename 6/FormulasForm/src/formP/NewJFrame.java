    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {
        try {
            double[] alpha = new double[5];
            alpha[0] = Double.parseDouble(jTextField1.getText());
            alpha[1] = Double.parseDouble(jTextField2.getText());
            alpha[2] = Double.parseDouble(jTextField3.getText());
            alpha[3] = Double.parseDouble(jTextField4.getText());
            alpha[4] = Double.parseDouble(jTextField5.getText());

            StringBuilder sb = new StringBuilder();

            sb.append("Вычисление z1 (цикл while):\n");
            int i = 0;
            while (i < 5) {
                double a = alpha[i];
                double z1 = 2 * Math.pow(Math.sin(3 * Math.PI - 2 * a), 2)
                        * Math.pow(Math.cos(5 * Math.PI + 2 * a), 2);
                sb.append("alpha=").append(a).append(", z1=").append(z1).append("\n");
                i++;
            }

            sb.append("\nВычисление z2 (цикл do-while):\n");
            i = 0;
            do {
                double a = alpha[i];
                double z2 = 1.0 / 4.0 - (1.0 / 4.0) * Math.sin(5.0 / 2.0 * Math.PI - 8 * a);
                sb.append("alpha=").append(a).append(", z2=").append(z2).append("\n");
                i++;
            } while (i < 5);

            sb.append("\nСравнение z1 и z2 (цикл for):\n");
            for (int j = 0; j < 5; j++) {
                double a = alpha[j];
                double z1 = 2 * Math.pow(Math.sin(3 * Math.PI - 2 * a), 2)
                        * Math.pow(Math.cos(5 * Math.PI + 2 * a), 2);
                double z2 = 1.0 / 4.0 - (1.0 / 4.0) * Math.sin(5.0 / 2.0 * Math.PI - 8 * a);
                sb.append("alpha=").append(a)
                        .append(", z1=").append(z1)
                        .append(", z2=").append(z2)
                        .append(", |z1-z2|=").append(Math.abs(z1 - z2))
                        .append("\n");
            }

            jTextArea1.setText(sb.toString());
        } catch (NumberFormatException ex) {
            jTextArea1.setText("Ошибка: введите 5 чисел.");
        }
    }

